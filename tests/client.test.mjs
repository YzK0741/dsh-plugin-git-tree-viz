import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
test('Client artifact follows the native closure-factory protocol and returns a Cordis contribution',async()=>{
  let registration;const context=vm.createContext({window:{__ModuleLoader__:{load:value=>{registration=value;}}}});
  const artifact=await readFile(new URL('../lib/client.js',import.meta.url),'utf8');
  assert.doesNotMatch(artifact,/new Function\(|eval\(|<iframe|srcdoc=/);
  vm.runInContext(artifact,context);assert.equal(registration.id,'dsh-plugin-git-tree-viz');
  const refs=[];let refIndex=0;const pendingEffects=[];
  const react={createElement:(type,props,...children)=>({type,props,children}),useSyncExternalStore:(_subscribe,getSnapshot)=>getSnapshot(),useRef:initial=>refs[refIndex++]??={current:initial},useEffect:fn=>pendingEffects.push(fn)};
  const plugin=registration.factory(name=>{assert.equal(name,'react');return react;});
  assert.equal(typeof plugin.apply,'function');assert.equal(typeof plugin.GitTreePanel,'function');
  const registrations=[],effects=[];
  const locale={register:()=>()=>{},bind:()=>key=>key,getSnapshot:()=>({active:'en'}),subscribe:()=>()=>{}};
  const themeSnapshot={active:{colorScheme:'dark'}};let themeListener;
  plugin.apply({effect:fn=>effects.push(fn()),on:(event,fn)=>{assert.equal(event,'theme/change');themeListener=fn;return ()=>{themeListener=undefined;};},slots:{inject:(slot,fn)=>fn(),register:(options,component)=>{registrations.push({options,component});return ()=>{};}},connection:{rpc:{call(){}},generation:{}},locale,theme:{getTheme:()=>themeSnapshot}});
  assert.deepEqual(registrations.map(row=>row.options.name),['conversation.view']);
  assert.equal(registrations[0].options.id,'git-tree-viz');assert.equal(registrations[0].options.order,30);
  const face=registrations[0].options.inject();
  assert.equal(face.theme.getSnapshot(),themeSnapshot);
  let updates=0;const unsubscribe=face.theme.subscribe(()=>updates++);
  themeListener(themeSnapshot);assert.equal(updates,1);unsubscribe();assert.equal(themeListener,undefined);
  let rows=[{workspaceId:'other',title:'Other',path:'C:/wrong',sessionIds:['other-session']},{workspaceId:'active',title:'Active',path:'C:/right/subdirectory',sessionIds:['active-session']}];
  const repositories=[];let cleared=0;
  const props={...face,sessionId:'active-session',generation:{subscribe:()=>()=>{},getSnapshot:()=>1},useWorkspaces:selector=>selector({items:rows}),t:key=>key};
  const render=()=>{refIndex=0;pendingEffects.length=0;plugin.GitTreePanel(props);refs[1].current={setLocale(){},setTheme(){},setRepository:repo=>repositories.push(repo),resetAccess(){cleared++;}};for(const effect of pendingEffects)effect();};
  render();assert.equal(repositories.at(-1),'C:/right/subdirectory');
  rows=[{...rows[1],path:'D:/moved-repository'}];render();assert.equal(repositories.at(-1),'D:/moved-repository');
  props.sessionId='unknown-session';render();assert.equal(repositories.at(-1),'');assert.equal(cleared,3);
});
